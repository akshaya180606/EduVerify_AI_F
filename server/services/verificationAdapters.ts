export const AVAILABLE_ADAPTERS: VerificationAdapter[] = [
  QRCodeVerificationAdapter,
  StatutoryReferenceAdapter,
  DigiLockerNADAdapter,
  StateLandRegistryAdapter,
];

/**
 * Dispatcher to execute external source verification against a document
 */
export async function executeAdapterVerification(
  document: DocumentRecord,
  institution: Institution,
  preferredAdapterId?: string
): Promise<AdapterVerificationResult> {
  let adapter = AVAILABLE_ADAPTERS.find(a => a.id === preferredAdapterId);

  if (!adapter) {
    // Select first matching adapter for document category
    if (document.extractedData?.qrPayload) {
      adapter = QRCodeVerificationAdapter;
    } else {
      adapter = AVAILABLE_ADAPTERS.find(a => a.supportedCategories.includes(document.category)) || StatutoryReferenceAdapter;
    }
  }

  return adapter.verify(document, institution);
}

